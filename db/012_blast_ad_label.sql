-- 012: 광고성 정보 여부를 발송마다 고른다
--
-- 지금까지 모든 발송을 광고성 정보로 보고 (광고) 표기와 수신거부 푸터를 강제로
-- 붙였다. 법을 지키는 쪽으로 기울인 기본값이지만, 이 판단은 코드가 아니라
-- 사람이 해야 한다.
--
-- 왜 중요한가: 네이버·다음·Gmail 은 제목의 "(광고)" 를 보고 광고/스팸 폴더로
-- 보낸다. 그게 필터의 의도된 동작이다. 그래서 법을 지키면 대다수가 광고함으로
-- 가고, 표기를 빼면 도달률은 오르지만 정보통신망법 §50 위반 위험을 진다.
-- 둘 다 만족하는 선택지는 없다 — 무엇을 보내는지에 따라 답이 갈린다.
--
-- 기본값은 true 로 둔다. 판단을 미룬 상태에서 나가는 메일은 표기가 있어야 한다.

ALTER TABLE blast ADD COLUMN IF NOT EXISTS is_ad boolean NOT NULL DEFAULT true;

COMMENT ON COLUMN blast.is_ad IS
  '영리목적 광고성 정보인가. true 면 제목에 (광고) 와 수신거부 푸터를 붙인다 (정보통신망법 §50).';
